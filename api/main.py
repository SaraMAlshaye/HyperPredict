"""FastAPI backend for the HyperPredict web app.

Run from the project root:
    python -m uvicorn api.main:app --reload --port 8000

All predictions come from the existing trained pipeline through
machine_learning/inference.py (load_artifacts, build_input_row, predict). This file
does no preprocessing of its own and never changes the model or its schema.

Endpoints
    GET  /api/health   model availability
    GET  /api/schema   input options and ranges, read from the saved feature schema
    POST /api/predict  one prediction for the 5 model features

If web/dist exists (after `npm run build`), the built React app is also served at /.
"""
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, ConfigDict, Field

from machine_learning.inference import build_input_row, load_artifacts, predict

ROOT = Path(__file__).resolve().parents[1]
WEB_DIST = ROOT / "web" / "dist"
DISCLAIMER = ("This result is generated by a machine-learning model for educational "
              "purposes only. It is not a medical diagnosis. Please consult a qualified "
              "healthcare professional for medical advice.")

_state: dict = {"model": None, "schema": None, "error": None}


def _load() -> None:
    try:
        _state["model"], _state["schema"] = load_artifacts()
        _state["error"] = None
    except FileNotFoundError as exc:
        _state["model"], _state["schema"], _state["error"] = None, None, str(exc)


@asynccontextmanager
async def lifespan(_: FastAPI):
    _load()
    yield


app = FastAPI(title="HyperPredict API", version="1.0.0", lifespan=lifespan)


def _require_model():
    if _state["model"] is None:
        raise HTTPException(status_code=503, detail=_state["error"] or "Model is not loaded.")
    return _state["model"], _state["schema"]


class PredictionRequest(BaseModel):
    """Exactly the model's five input features. Any other field is rejected (422),
    so height, weight, SpO2 or blood pressure can never reach the model."""

    model_config = ConfigDict(extra="forbid")

    Age_Years: float = Field(..., description="Age in years (18-80; 80 means 80 or older)")
    BMI: float | None = Field(None, description="Body mass index, kg/m²")
    Pulse_BPM: float | None = Field(None, description="Resting pulse, beats per minute")
    Sex: str
    Race_Ethnicity: str


class PredictionResponse(BaseModel):
    label: int
    label_text: str
    probability: float
    decision_threshold: float
    model_name: str
    schema_version: int
    inputs: dict
    disclaimer: str


@app.get("/api/health")
def health() -> dict:
    schema = _state["schema"]
    return {
        "status": "ok" if schema else "model_unavailable",
        "model_loaded": schema is not None,
        "model_name": schema["model_name"] if schema else None,
        "schema_version": schema.get("schema_version") if schema else None,
        "detail": _state["error"],
    }


@app.get("/api/schema")
def schema() -> dict:
    _, s = _require_model()
    return {
        "model_name": s["model_name"],
        "schema_version": s.get("schema_version"),
        "feature_columns": s["feature_columns"],
        "numeric_inputs": s["numeric_inputs"],
        "categorical_options": s["categorical_options"],
        "decision_threshold": s["decision_threshold"],
        "target_labels": s["target_labels"],
        "test_metrics": s["test_metrics"],
        "test_rows": s["test_rows"],
        "disclaimer": DISCLAIMER,
    }


@app.post("/api/predict", response_model=PredictionResponse)
def predict_endpoint(request: PredictionRequest) -> PredictionResponse:
    model, s = _require_model()
    values = request.model_dump()
    row, errors = build_input_row(values, s)  # existing schema validation
    if errors:
        raise HTTPException(status_code=422, detail=errors)
    result = predict(model, s, row)           # existing fitted pipeline
    return PredictionResponse(
        label=result["label"],
        label_text=result["label_text"],
        probability=result["probability"],
        decision_threshold=s["decision_threshold"],
        model_name=s["model_name"],
        schema_version=s.get("schema_version"),
        inputs={k: (None if v != v else v) for k, v in row.iloc[0].to_dict().items()},
        disclaimer=DISCLAIMER,
    )


# Serve the production build of the React app, if it has been built.
if WEB_DIST.exists():
    app.mount("/assets", StaticFiles(directory=WEB_DIST / "assets"), name="assets")

    @app.get("/{path:path}", include_in_schema=False)
    def spa(path: str):
        file = (WEB_DIST / path).resolve()
        if path and file.is_file() and WEB_DIST.resolve() in file.parents:
            return FileResponse(file)
        if path.startswith("api/"):
            raise HTTPException(status_code=404, detail="Not found")
        return FileResponse(WEB_DIST / "index.html")
