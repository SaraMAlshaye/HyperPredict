import type { ReactNode } from "react";
import { Button } from "./Button";
import { Icon } from "./Icon";
import { Pulsie } from "./Pulsie";

export function LoadingState({ message }: { message: string }) {
  return (
    <div className="state" role="status" aria-live="polite">
      <span className="spinner" aria-hidden="true" />
      <p>{message}</p>
    </div>
  );
}

export function ErrorState({ title, message, details = [], onRetry }: {
  title: string; message: string; details?: string[]; onRetry?: () => void;
}) {
  return (
    <div className="state state--error" role="alert">
      <span className="state__icon"><Icon name="alert" size={26} /></span>
      <h2>{title}</h2>
      <p>{message}</p>
      {details.length > 0 && <ul className="state__details">{details.map((d) => <li key={d}>{d}</li>)}</ul>}
      {onRetry && <Button variant="secondary" icon="refresh" onClick={onRetry}>Try again</Button>}
    </div>
  );
}

export function EmptyState({ title, message, action }: { title: string; message: string; action?: ReactNode }) {
  return (
    <div className="state state--empty">
      <Pulsie size="md" />
      <h2>{title}</h2>
      <p>{message}</p>
      {action}
    </div>
  );
}

export const DISCLAIMER =
  "This result is generated by a machine-learning model for educational purposes only. " +
  "It is not a medical diagnosis. Please consult a qualified healthcare professional for medical advice.";

export function Disclaimer({ text = DISCLAIMER }: { text?: string }) {
  return (
    <aside className="disclaimer">
      <Icon name="info" size={20} />
      <p>{text}</p>
    </aside>
  );
}
